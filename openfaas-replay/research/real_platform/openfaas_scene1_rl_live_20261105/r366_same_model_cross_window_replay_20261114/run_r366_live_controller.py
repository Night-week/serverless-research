def choose_decision(block: dict, stream: dict) -> dict:
    """Load the seed/window target and reconstruct EASR from the t=15 prefix."""
    initial = _layout(block["initials"][INITIAL_INDEX])
    targets = json.loads(TARGETS_FILE.read_text())
    rows = [row for row in targets if int(row["seed"]) == SEED
            and row["stream_id"] == STREAM_ID]
    if len(rows) != 1:
        raise RuntimeError(f"R361 target missing/duplicated for seed={SEED}, stream={STREAM_ID}")
    target_row = rows[0]
    pressure = rf_route = pressure_override = ppo_action = None
    policy_hash = rf_hash = grl_hash = None
    decision_observables = {}
    if METHOD in {"easr", "easr_no_pressure"}:
        D, E = learning_context()
        net, model_hash = E.load_policy(SEED)
        if not R363_RF_PATH.is_file() or not R363_HELDOUT_PATH.is_file():
            raise FileNotFoundError("R363 calibrated RF or heldout decision audit is missing")
        gate = E.R.joblib.load(R363_RF_PATH)
        engine = E.Engine(copy.deepcopy(block["profile"]), initial, AzureArrivals(stream))
        engine._trace_past = list(stream["history_seconds"])
        engine.advance(DECISION_SECONDS)
        decision_observables = trace_decision_diagnostics(engine, stream, DECISION_SECONDS)
        features = D.trace_feature_vector(engine, net)
        classes = list(gate.classes_)
        if 1 not in classes:
            raise RuntimeError("R363 RF has no positive Whole32 class")
        rf_whole_probability = float(gate.predict_proba([features])[0][classes.index(1)])
        rf_route = rf_whole_probability >= RF_PROBABILITY_THRESHOLD
        pressure = math.sinh(features[-3])
        pool = B.neighbors(block["profile"], engine.layout)
        observed = E.R.observe(engine, pool, 0)
        with E.torch.no_grad():
            logits = net(E.torch.tensor(observed, dtype=E.torch.float32))[0]
            ppo_action = int(logits.argmax())
        rf_hash = D.sha(R363_RF_PATH)
        heldout = json.loads(R363_HELDOUT_PATH.read_text())
        if not math.isclose(float(heldout["selected_validation_threshold"]),
                            RF_PROBABILITY_THRESHOLD, rel_tol=0.0, abs_tol=1e-12):
            raise RuntimeError("R366 RF threshold differs from the locked R363 validation threshold")
        audit_matches = [row for row in heldout["cases"]
                         if int(row["seed"]) == SEED and row["stream_id"] == STREAM_ID]
        if len(audit_matches) != 1:
            raise RuntimeError("R363 heldout audit has no unique seed/window decision")
        r363_audit = audit_matches[0]
        expected_rf_hash = EXPECTED_RF_HASHES.get(SEED)
        if (expected_rf_hash is None or rf_hash != expected_rf_hash
                or model_hash != target_row["policy_sha256"]):
            raise RuntimeError("R363 RF or frozen R361 PPO hash differs from the replay binding")
        if (not math.isclose(rf_whole_probability, float(r363_audit["whole_probability"]),
                             rel_tol=1e-8, abs_tol=1e-8)
                or not math.isclose(pressure, float(r363_audit["pressure"]),
                                    rel_tol=1e-8, abs_tol=1e-8)
                or ppo_action != int(r363_audit["ppo_action_index"])):
            raise RuntimeError("R366 recomputed decision differs from R363 frozen heldout audit")
        pressure_would_trigger = pressure > 1.0
        pressure_override = METHOD == "easr" and pressure_would_trigger
        system_route = "whole32" if (rf_route or pressure_override) else "ppo"
        if system_route == "whole32":
            whole_record = target_row["methods"]["whole32"]
            selected = tuple(tuple(int(value) for value in part)
                             for part in whole_record["layout"])
        else:
            selected = pool[ppo_action]
        if METHOD == "easr":
            audit_layout_value = (r363_audit["whole32_layout"] if system_route == "whole32"
                                  else r363_audit["local_layout"])
            audit_layout = tuple(tuple(int(value) for value in part)
                                 for part in audit_layout_value)
            audit_route = r363_audit["route_with_tuned_threshold"]
            if (selected != audit_layout
                    or system_route != ("whole32" if audit_route == "whole32" else "ppo")
                    or rf_route != (float(r363_audit["whole_probability"]) >= RF_PROBABILITY_THRESHOLD)
                    or pressure_override != bool(r363_audit["pressure_override"])
                    or ppo_action != int(r363_audit["ppo_action_index"])
                    or model_hash != target_row["policy_sha256"]
                    or rf_hash != expected_rf_hash):
                raise RuntimeError("live t=15 EASR decision differs from the frozen R363 audit")
            record = {"layout": [list(selected[0]), list(selected[1])],
                      "service_count": len(B.groups(selected[0])),
                      "source": "R363 calibrated RF plus frozen R361 PPO"}
        else:
            record = {"layout": [list(selected[0]), list(selected[1])],
                      "service_count": len(B.groups(selected[0]))}
        route = system_route
        route_reason = (f"live_t15_rf_probability={rf_whole_probability:.6f}"
                        f">={RF_PROBABILITY_THRESHOLD:.2f}:{rf_route}"
                        f"_pressure={pressure:.6f}>1.0:{pressure_override}_ppo_action={ppo_action}")
        policy_hash = model_hash
    else:
        record = target_row["methods"][METHOD]
        selected = tuple(tuple(int(value) for value in part) for part in record["layout"])
        route = METHOD
        route_reason = "frozen_seed_and_heldout_window_grl_layout"
        key = "grl_native_sha256" if METHOD == "grl_native" else "grl_response_sha256"
        grl_hash = target_row[key]
        checkpoint = R361_ARTIFACT_DIR / "outputs" / METHOD / f"seed_{SEED}" / "selected.pt"
        if not checkpoint.is_file():
            raise RuntimeError(f"GRL checkpoint missing: {checkpoint}")
        digest = hashlib.sha256(checkpoint.read_bytes()).hexdigest()
        if digest != grl_hash:
            raise RuntimeError(f"GRL checkpoint hash mismatch for {METHOD}/seed={SEED}")
    if not B.valid(block["profile"], *selected):
        raise RuntimeError(f"frozen {METHOD} target is infeasible for this profile")
    return {
        "method": METHOD,
        "seed": SEED,
        "profile_id": PROFILE_ID,
        "stream_id": STREAM_ID,
        "arrival_count": len(stream["arrivals_seconds"]),
        "decision_at_s": DECISION_SECONDS,
        "route": route,
        "route_reason": route_reason,
        "initial_layout": initial,
        "selected_layout": selected,
        "policy_sha256": policy_hash,
        "rf_sha256": rf_hash,
        "grl_sha256": grl_hash,
        "pressure": pressure,
        "ppo_action_index": ppo_action,
        "rf_route_whole": rf_route,
        "rf_whole_probability": rf_whole_probability if METHOD in {"easr", "easr_no_pressure"} else None,
        "rf_probability_threshold": RF_PROBABILITY_THRESHOLD if METHOD in {"easr", "easr_no_pressure"} else None,
        "ready_cost_proxy_seconds": READY_COST_PROXY_SECONDS if METHOD in {"easr", "easr_no_pressure"} else None,
        "pressure_override": pressure_override,
        "pressure_rule_enabled": METHOD == "easr",
        "decision_observables": decision_observables,
        "target_detail": {k: v for k, v in target_row.items()
                          if k not in {"methods", "initial_layout"}},
        "decision_state_source": "R363 calibrated-cost RF and frozen R361 PPO on the held-out t=15 replay snapshot",
    }


def service_names(layout: tuple, stage: str, profile: dict) -> list[dict]:
    groups = B.groups(layout[0])
    counts = [sum(len(nodes) for idx, nodes in enumerate(groups)
                  if layout[1][idx] == site) for site in (0, 1)]
    suffix = hashlib.sha256(json.dumps(layout, separators=(",", ":")).encode()).hexdigest()[:6]
    result = []
    for idx, nodes in enumerate(groups):
        site = layout[1][idx]
        pool = "edge" if site == 0 else "cloud"
        nsite = max(1, counts[site])
        cpu_m = max(100, round(1000 * profile["cores"][site] * len(nodes) / nsite))
        mem_mib = max(64, round(profile["ram"][site] * len(nodes) / nsite))
        name = f"{SERVICE_PREFIX}-{stage}-{suffix}-g{idx:02d}-{pool}-20261108"
        result.append({"name": name, "group": idx, "nodes": nodes, "site": site,
                       "pool": pool, "cpu_m": cpu_m, "memory_mib": mem_mib})
    return result


