def function_resources_exist(name: str) -> bool:
    deployment = M.kubectl("-n", "openfaas-fn", "get", "deployment", name, check=False)
    service = M.kubectl("-n", "openfaas-fn", "get", "service", name, check=False)
    return deployment.returncode == 0 and service.returncode == 0


def wait_for_function_resources(name: str) -> float | None:
    """Reconcile delayed faas-netes creates after a gateway 502/transport error."""
    started = time.perf_counter()
    deadline = time.monotonic() + DEPLOY_API_RECOVERY_WAIT_SECONDS
    while time.monotonic() < deadline:
        if function_resources_exist(name):
            return time.perf_counter() - started
        time.sleep(DEPLOY_API_RECOVERY_POLL_SECONDS)
    if function_resources_exist(name):
        return time.perf_counter() - started
    return None


def deploy_layout(layout: tuple, stage: str, created: list[str], profile: dict) -> dict:
    entries = service_names(layout, stage, profile)
    started_all = time.perf_counter()
    created.extend(entry["name"] for entry in entries)

    def deploy_one(entry: dict) -> dict:
        name = entry["name"]
        body = {
            "service": name,
            "image": M.IMAGE,
            "envVars": {},
            "labels": {"com.openfaas.scale.min": "1", "com.openfaas.scale.max": "1"},
            "annotations": {},
            "requests": {"cpu": f"{entry['cpu_m']}m", "memory": f"{entry['memory_mib']}Mi"},
            "limits": {"cpu": f"{entry['cpu_m']}m", "memory": f"{entry['memory_mib']}Mi"},
            "secrets": [],
        }
        started = time.perf_counter()
        api_started = time.perf_counter()
        transport_error = None
        try:
            status, response = M.api("POST", "/system/functions", body)
        except (urllib.error.URLError, TimeoutError, ConnectionError) as exc:
            status, response = None, b""
            transport_error = f"{type(exc).__name__}: {exc}"
        recovered_after_gateway_error = False
        api_recovery_wait = 0.0
        if status not in (200, 201, 202):
            transient = status in (502, 503, 504) or transport_error is not None
            if transient:
                say(f"R366_DEPLOY_API_TRANSIENT service={name} http_status={status} "
                    f"reconcile_wait_seconds={DEPLOY_API_RECOVERY_WAIT_SECONDS}")
                waited = wait_for_function_resources(name)
                if waited is not None:
                    recovered_after_gateway_error = True
                    api_recovery_wait = waited
                    say(f"R366_DEPLOY_API_RECOVERED service={name} "
                        f"reconcile_wait_seconds={waited:.3f}")
                else:
                    detail = transport_error or f"HTTP {status}: {response[:240]!r}"
                    raise RuntimeError(f"OpenFaaS POST {name} failed; no Deployment/Service "
                                       f"appeared after {DEPLOY_API_RECOVERY_WAIT_SECONDS}s: {detail}")
            else:
                raise RuntimeError(f"OpenFaaS POST {name}: HTTP {status}: {response[:240]!r}")
        M.kubectl("-n", "openfaas-fn", "rollout", "status", f"deployment/{name}",
                  "--timeout=300s")
        row = {**entry, "http_status": status,
               "api_transport_error": transport_error,
               "api_recovered_after_gateway_error": recovered_after_gateway_error,
               "api_recovery_wait_seconds": api_recovery_wait,
               "api_call_elapsed_seconds": time.perf_counter() - api_started,
               "ready_seconds": time.perf_counter() - started}
        say(f"R366_DEPLOY_READY stage={stage} service={name} seconds={row['ready_seconds']:.3f}")
        return row

    # Start the independent OpenFaaS Deployments together and measure the
    # service-set makespan, which is the time until the final service is Ready.
    with cf.ThreadPoolExecutor(max_workers=max(1, len(entries))) as pool:
        records = list(pool.map(deploy_one, entries))
    return {"services": records, "ready_wall_seconds": time.perf_counter() - started_all,
            "parallel_start": True, "ready_wall_definition": "parallel makespan until all target services Ready"}


def remove_names(names: list[str]) -> float:
    started = time.perf_counter()
    for name in names:
        M.kubectl("-n", "openfaas-fn", "delete", f"deployment/{name}", f"service/{name}",
                  "--ignore-not-found=true", "--wait=true", "--timeout=180s", check=False)
    return time.perf_counter() - started


def run_layout_workflow(layout: tuple, services: list[dict], profile: dict,
                        workflow_id: str) -> dict:
    groups = B.groups(layout[0])
    node_to_group = {node: idx for idx, nodes in enumerate(groups) for node in nodes}
    edges = M.topology_edges(profile, "diamond")
    succ = [set() for _ in groups]
    parents = [set() for _ in groups]
    incoming = [0] * len(groups)
    for source, target, size in edges:
        left, right = node_to_group[source], node_to_group[target]
        if left != right:
            succ[left].add(right)
            parents[right].add(left)
            incoming[right] += size
    order = M.topological_order(len(groups), [(u, v, 1) for u in range(len(groups))
                                               for v in succ[u]])
    service_by_group = {entry["group"]: entry["name"] for entry in services}
    finished: set[int] = set()
    checksums: dict[str, dict] = {}
    calls = 0
    started = time.perf_counter()
    while len(finished) < len(groups):
        ready = [idx for idx in order if idx not in finished and parents[idx] <= finished]
        if not ready:
            raise RuntimeError("group DAG scheduler made no progress")
        with cf.ThreadPoolExecutor(max_workers=len(ready)) as pool:
            futures = {
                pool.submit(M.invoke, service_by_group[idx], workflow_id, idx, profile,
                            groups[idx], incoming[idx]): idx
                for idx in ready
            }
            for future in cf.as_completed(futures):
                result = future.result()
                checksums.update(M.checksum_map(result))
                finished.add(futures[future])
                calls += 1
    if len(checksums) != len(profile["work"]):
        raise RuntimeError(f"workflow returned {len(checksums)}/{len(profile['work'])} function checksums")
    return {"elapsed_seconds": time.perf_counter() - started,
            "checksums": checksums, "function_calls": calls}


class DispatchGate:
    def __init__(self, initial_layout: tuple, initial_stage: str):
        self.condition = threading.Condition()
        self.current_layout = initial_layout
        self.current_stage = initial_stage
        self.paused = False
        self.active = 0
        self.completed = 0
        self.decision_ready = threading.Event()
        self.failure: str | None = None

    def acquire(self, needs_decision: bool) -> tuple:
        if needs_decision:
            self.decision_ready.wait()
        with self.condition:
            if self.failure:
                raise RuntimeError(self.failure)
            while self.paused:
                self.condition.wait()
                if self.failure:
                    raise RuntimeError(self.failure)
            self.active += 1
            return self.current_layout, self.current_stage

    def release(self) -> None:
        with self.condition:
            self.active -= 1
            self.completed += 1
            if self.active == 0:
                self.condition.notify_all()

    def pause_and_drain(self) -> float:
        started = time.perf_counter()
        with self.condition:
            self.paused = True
            while self.active:
                self.condition.wait()
        return time.perf_counter() - started

    def resume(self, layout: tuple, stage: str) -> None:
        with self.condition:
            self.current_layout = layout
            self.current_stage = stage
            self.paused = False
            self.decision_ready.set()
            self.condition.notify_all()

    def abort(self, message: str) -> None:
        with self.condition:
            self.failure = message
            self.paused = False
            self.decision_ready.set()
            self.condition.notify_all()


def request_worker(index: int, arrival: float, epoch: float, gate: DispatchGate,
                   profile: dict, service_map: dict[str, list[dict]]) -> dict:
    target = epoch + arrival
    time.sleep(max(0.0, target - time.perf_counter()))
    needs_decision = arrival >= DECISION_SECONDS
    layout, stage = gate.acquire(needs_decision)
    dispatched = time.perf_counter()
    workflow_id = f"{RUN_TAG}_{index:04d}"
    try:
        result = run_layout_workflow(layout, service_map[stage], profile, workflow_id)
        completed = time.perf_counter()
        return {"request_index": index, "source_arrival_s": arrival,
                "dispatch_lag_s": max(0.0, dispatched - target), "stage": stage,
                "latency_after_dispatch_s": result["elapsed_seconds"],
                "latency_from_scheduled_arrival_s": completed - target,
                "function_calls": result["function_calls"],
                "checksums": result["checksums"], "error": None}
    except Exception as exc:
        completed = time.perf_counter()
        return {"request_index": index, "source_arrival_s": arrival,
                "dispatch_lag_s": max(0.0, dispatched - target), "stage": stage,
                "latency_after_dispatch_s": None,
                "latency_from_scheduled_arrival_s": completed - target,
                "function_calls": 0, "checksums": None,
                "error": type(exc).__name__ + ": " + str(exc)[:300]}
    finally:
        gate.release()


def image_cached() -> dict:
    result = M.subprocess.run(["k3s", "ctr", "images", "list", "-q"], text=True,
                              stdout=M.subprocess.PIPE, stderr=M.subprocess.PIPE, check=False)
    return {"cached": any(M.IMAGE in row or M.IMAGE.split("@")[0] in row
                           for row in result.stdout.splitlines()),
            "query_returncode": result.returncode, "image": M.IMAGE}


def preflight(decision: dict) -> dict:
    bundle, block, stream = load_inputs()
    profile = block["profile"]
    M.kubectl("get", "nodes")
    gateway_status, _gateway_body = M.api("GET", "/system/functions")
    if gateway_status != 200:
        raise RuntimeError(f"OpenFaaS gateway is not ready: HTTP {gateway_status}")
    current = json.loads(M.kubectl("-n", "openfaas-fn", "get", "services", "-o", "json").stdout)
    existing = {row["metadata"]["name"] for row in current.get("items", [])}
    init_entries = service_names(decision["initial_layout"], "initial", profile)
    target_entries = service_names(decision["selected_layout"], "policy", profile)
    collisions = sorted(existing & {row["name"] for row in init_entries + target_entries})
    if collisions:
        raise RuntimeError(f"R366 service-name collision: {collisions}")
    max_new = max(len(init_entries), len(target_entries))
    if len(existing) + max_new > SERVICE_CAP:
        raise RuntimeError(f"R366 would exceed OpenFaaS service cap: {len(existing)}+{max_new}>{SERVICE_CAP}")
    quota = M.kubectl("-n", "openfaas-fn", "get", "resourcequota", QUOTA_NAME, check=False)
    cached = image_cached()
    if not cached["cached"]:
        raise RuntimeError("benchmark image is not cached on the node")
    return {"run_tag": RUN_TAG, "method": METHOD, "seed": SEED,
            "controller_sha256": D.sha(Path(__file__)),
            "gateway_http_status": gateway_status,
            "profile_id": PROFILE_ID, "family": block["profile"]["family"],
            "stream_id": STREAM_ID, "requests": len(stream["arrivals_seconds"]),
            "client_workers": CLIENT_WORKERS,
            "initial_services": init_entries, "selected_services": target_entries,
            "existing_services": sorted(existing), "service_cap": SERVICE_CAP,
            "service_name_collisions": collisions,
            "quota_already_exists": quota.returncode == 0,
            "image": cached, "trace_bundle_sha256": D.sha(TRACE_FILE),
            "model_decision": {k: v for k, v in decision.items()
                               if k not in ("initial_layout", "selected_layout", "predicted_scenario_metrics")}}


def summarize_requests(rows: list[dict]) -> dict:
    output = {}
    for stage in ("initial", "policy"):
        selected = [row for row in rows if row["stage"] == stage and row["error"] is None]
        output[stage] = {
            "successes": len(selected),
            "errors": sum(row["stage"] == stage and row["error"] is not None for row in rows),
            "mean_response_from_scheduled_arrival_s": statistics.mean(
                row["latency_from_scheduled_arrival_s"] for row in selected) if selected else None,
            "p95_response_from_scheduled_arrival_s": percentile(
                [row["latency_from_scheduled_arrival_s"] for row in selected], .95),
            "mean_execution_after_dispatch_s": statistics.mean(
                row["latency_after_dispatch_s"] for row in selected) if selected else None,
        }
    successes = [row for row in rows if row["error"] is None]
    output["all"] = {
        "successes": len(successes), "errors": len(rows) - len(successes),
        "mean_response_from_scheduled_arrival_s": statistics.mean(
            row["latency_from_scheduled_arrival_s"] for row in successes) if successes else None,
        "p95_response_from_scheduled_arrival_s": percentile(
            [row["latency_from_scheduled_arrival_s"] for row in successes], .95),
        "mean_dispatch_lag_s": statistics.mean(row["dispatch_lag_s"] for row in rows) if rows else None,
    }
    return output


def main() -> None:
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument("--preflight", action="store_true")
    args = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    bundle, block, stream = load_inputs()
    decision = choose_decision(block, stream)
    check = preflight(decision)
    PREFLIGHT_FILE.parent.mkdir(parents=True, exist_ok=True)
    PREFLIGHT_FILE.write_text(json.dumps(check, ensure_ascii=False, indent=2) + "\n")
    if args.preflight:
        print(json.dumps(check, ensure_ascii=False, indent=2), flush=True)
        return

    profile = block["profile"]
    initial = decision["initial_layout"]
    target = decision["selected_layout"]
    init_stage = "initial"
    target_stage = "policy" if target != initial else init_stage
    init_services = service_names(initial, init_stage, profile)
    target_services = service_names(target, target_stage, profile) if target != initial else init_services
    created: list[str] = []
    rows: list[dict] = []
    transition = {}
    warm_checksums = {}
    gate = DispatchGate(initial, init_stage)
    started_at = time.time()
    try:
        create_quota()
        init_deploy = deploy_layout(initial, init_stage, created, profile)
        init_map = {init_stage: init_services}
        initial_warmup = run_layout_workflow(
            initial, init_services, profile, "r352-warm-initial")
        initial_warmup_seconds = initial_warmup["elapsed_seconds"]
        warm_checksums[init_stage] = initial_warmup["checksums"]
        say(f"R366_INITIAL_READY services={len(init_services)} seconds={init_deploy['ready_wall_seconds']:.3f}")

        epoch = time.perf_counter() + 0.5
        cutoff = epoch + DECISION_SECONDS
        say(f"R366_TRACE_START stream={STREAM_ID} requests={len(stream['arrivals_seconds'])}")
        with cf.ThreadPoolExecutor(max_workers=CLIENT_WORKERS) as pool:
            futures = [pool.submit(request_worker, i, arrival, epoch, gate, profile, init_map)
                       for i, arrival in enumerate(stream["arrivals_seconds"])]
            time.sleep(max(0.0, cutoff - time.perf_counter()))
            decision_started = time.perf_counter()
            actual_decision_time_s = decision_started - epoch
            due_by_decision = sum(float(a) <= DECISION_SECONDS
                                  for a in stream["arrivals_seconds"])
            with gate.condition:
                live_active = gate.active
                live_completed = gate.completed
                live_paused = gate.paused
            live_snapshot = {
                "decision_clock_s": actual_decision_time_s,
                "scheduled_arrivals_due_by_t15": due_by_decision,
                "completed_workflows_before_decision": live_completed,
                "active_openfaas_workflows_at_decision": live_active,
                "due_but_not_completed_or_active_estimate": max(
                    0, due_by_decision - live_completed - live_active),
                "dispatch_gate_paused_before_decision": live_paused,
                "semantics": "replay-harness estimate from scheduled due count minus completed and active workflows; not internal OpenFaaS queue telemetry",
            }
            try:
                # Decide from the t=15 observed prefix before pausing active work.
                # If the selected target is unchanged, no drain or redeployment is needed.
                decision = choose_decision(block, stream)
                decision["live_replay_snapshot_at_decision"] = live_snapshot
                decision_seconds = time.perf_counter() - decision_started
                target = decision["selected_layout"]
                target_stage = "policy" if target != initial else init_stage
                target_services = service_names(target, target_stage, profile) if target != initial else init_services
                init_map[target_stage] = target_services
                say(f"R366_CONTROL_DECISION route={decision['route']} reason={decision['route_reason']} "
                    f"groups={len(target_services)} inference_seconds={decision_seconds:.3f}")

                if target != initial:
                    drain_wait = gate.pause_and_drain()
                    say(f"R366_DRAIN_COMPLETE active_drain={drain_wait:.3f}s")
                    teardown = remove_names([row["name"] for row in init_services])
                    deploy = deploy_layout(target, target_stage, created, profile)
                    target_warmup = run_layout_workflow(
                        target, target_services, profile, "r352-warm-target")
                    target_warmup_seconds = target_warmup["elapsed_seconds"]
                    warm_checksums[target_stage] = target_warmup["checksums"]
                    if warm_checksums[init_stage] != warm_checksums[target_stage]:
                        raise RuntimeError("initial/selected layouts produced different warmup checksums")
                    gate.resume(target, target_stage)
                    dispatch_released_at = time.perf_counter()
                    transition = {
                        "changed_layout": True,
                        "decision_seconds": decision_seconds,
                        "drain_seconds": drain_wait,
                        "old_layout_teardown_seconds": teardown,
                        "target_layout_ready_seconds": deploy["ready_wall_seconds"],
                        "target_warmup_seconds": target_warmup_seconds,
                        "total_pause_seconds": time.perf_counter() - decision_started,
                        "target_deployment": deploy,
                    }
                else:
                    warm_checksums[target_stage] = warm_checksums[init_stage]
                    gate.resume(initial, init_stage)
                    dispatch_released_at = time.perf_counter()
                    transition = {
                        "changed_layout": False,
                        "decision_seconds": decision_seconds,
                        "drain_seconds": 0.0,
                        "old_layout_teardown_seconds": 0.0,
                        "target_layout_ready_seconds": 0.0,
                        "target_warmup_seconds": 0.0,
                        "total_pause_seconds": time.perf_counter() - decision_started,
                    }
                actual_dispatch_pause = max(
                    0.0, dispatch_released_at - epoch - DECISION_SECONDS)
                transition["dispatch_release_at_workload_s"] = dispatch_released_at - epoch
                transition["actual_dispatch_pause_from_t15_seconds"] = actual_dispatch_pause
                decision["actual_dispatch_pause_from_t15_seconds"] = actual_dispatch_pause
            except Exception as exc:
                gate.abort(f"R366 controller transition failed: {type(exc).__name__}: {exc}")
                raise

            for future in cf.as_completed(futures):
                rows.append(future.result())
                if len(rows) % 50 == 0:
                    say(f"R366_REQUESTS_COMPLETED {len(rows)}/{len(futures)}")

        failures = [row for row in rows if row["error"] is not None]
        mismatch = [row for row in rows if row["error"] is None
                    and row["checksums"] != warm_checksums[row["stage"]]]
        result = {
            "experiment": "R366_CALIBRATED_CROSS_WINDOW_REPLAY",
            "run_tag": RUN_TAG,
            "method": METHOD,
            "seed": SEED,
            "started_unix": started_at,
            "total_lifecycle_elapsed_seconds": time.time() - started_at,
            "platform": {"provider": "OpenFaaS CE", "deployment": "single-node K3s",
                         "node": "single-node-testbed", "old_pilot_services_untouched": True,
                         "new_services_removed_after_run": True},
            "controller_decision": decision,
            "workload": {"trace_source": "Azure Functions 2019 minute-count-driven ingress proxy",
                         "trace_window": STREAM_ID, "requests": len(stream["arrivals_seconds"]),
                         "window_seconds": 60, "decision_seconds": DECISION_SECONDS,
                         "within_minute_times_interpolated": True,
                         "client_workers": CLIENT_WORKERS},
            "layouts": {"initial": init_services, "policy_selected": target_services},
            "initial_deployment": init_deploy,
            "initial_deployment_ready_wall_seconds": init_deploy["ready_wall_seconds"],
            "initial_warmup_seconds": initial_warmup_seconds,
            "controller_inference_seconds": decision_seconds,
            "transition": transition,
            "warmup_checksums_match": warm_checksums.get(init_stage) == warm_checksums.get(target_stage),
            "all_measured_checksums_match": not mismatch,
            "checksum_mismatches": len(mismatch),
            "all_requests_succeeded": not failures,
            "summary": summarize_requests(rows),
            "requests": rows,
            "errors": failures,
            "scope": "Eight-function single-node OpenFaaS replay of the same seed-631 EASR controller on two Azure-derived held-out windows, with three serial repetitions per window interleaved by the R366 runner. The R363 calibrated RF threshold is 0.34, pressure threshold 1.0, and decision time 15s. Images are cached and Edge/Cloud are logical labels on one node; this does not measure cold image transfer or cross-node networking.",
        }
        OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT_FILE.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n")
        say(json.dumps({"output": str(OUTPUT_FILE), "run_tag": RUN_TAG, "method": METHOD,
                        "all_requests_succeeded": result["all_requests_succeeded"],
                        "summary": result["summary"], "transition": transition},
                       ensure_ascii=False))
        if failures or mismatch:
            raise SystemExit(2)
    finally:
        remove_names(created)
        M.kubectl("-n", "openfaas-fn", "delete", "resourcequota", QUOTA_NAME,
                  "--ignore-not-found=true", check=False)
        say("R366_CLEANUP_FINISHED")


if __name__ == "__main__":
    main()
