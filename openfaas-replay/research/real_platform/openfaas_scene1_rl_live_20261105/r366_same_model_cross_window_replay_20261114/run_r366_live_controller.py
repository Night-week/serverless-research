def percentile(values: list[float], q: float) -> float | None:
    if not values:
        return None
    ordered = sorted(values)
    return ordered[max(0, math.ceil(q * len(ordered)) - 1)]


def trace_decision_diagnostics(engine, stream: dict, decision_s: float) -> dict:
    """Record the trace-driven model snapshot separately from live OpenFaaS state."""
    arrivals = sorted(float(t) for t in stream["arrivals_seconds"])
    prefix = [t for t in arrivals if t <= decision_s]
    history = [float(t) for t in stream.get("history_seconds", [])]
    known = history + prefix
    recent10 = [t for t in known if decision_s - 10 < t <= decision_s]
    recent5 = [t for t in prefix if decision_s - 5 < t <= decision_s]

    def peak_count(width: float) -> int:
        best = left = 0
        for right, value in enumerate(prefix):
            while value - prefix[left] >= width:
                left += 1
            best = max(best, right - left + 1)
        return best

    gaps = [prefix[i] - prefix[i - 1] for i in range(1, len(prefix))]
    gap_cv = (statistics.pstdev(gaps) / statistics.mean(gaps)
              if len(gaps) > 1 and statistics.mean(gaps) > 0 else None)
    return {
        "decision_time_s": decision_s,
        "scheduled_arrivals_by_decision": len(prefix),
        "mean_arrival_rate_per_s_since_start": len(prefix) / max(decision_s, 1.0),
        "arrivals_last_5s": len(recent5),
        "arrival_rate_last_5s_per_s": len(recent5) / min(5.0, decision_s),
        "arrivals_last_10s_including_history": len(recent10),
        "arrival_rate_last_10s_per_s": len(recent10) / min(10.0, decision_s),
        "prefix_arrivals_in_5s_buckets": [
            sum(0 <= t < 5 for t in prefix),
            sum(5 <= t < 10 for t in prefix),
            sum(10 <= t <= decision_s for t in prefix),
        ],
        "peak_prefix_arrivals_in_1s": peak_count(1.0),
        "peak_prefix_arrivals_in_3s": peak_count(3.0),
        "prefix_interarrival_gap_cv": gap_cv,
        "trace_simulated_active_workflows": int(engine.active),
        "trace_simulated_backlog_workflows": len(engine.backlog),
        "trace_simulator_source": "R329 trace-driven event simulation; not Kubernetes/OpenFaaS internal queue telemetry",
    }


